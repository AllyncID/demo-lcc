function rounded(icon: IconSvgElement) {
  return function Icon({ size = 24, ...props }: Omit<HugeiconsIconProps, 'icon'>) {
    return <HugeiconsIcon icon={icon} size={size} strokeWidth={1.7} strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" data-icon-family="hugeicons-stroke-rounded" {...props}/>;
  };
}

